import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const config = JSON.parse(await readFile(join(root, "app.config.json"), "utf8"));
const runtimeConfig = { ...config, shortName: config.appName };

await writeFile(
  join(root, "app-config.js"),
  `// Generated by scripts/sync-app-config.mjs from app.config.json.\nwindow.APP_CONFIG = Object.freeze(${JSON.stringify(runtimeConfig)});\n`,
  "utf8"
);

const manifestPath = join(root, "manifest.webmanifest");
const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
Object.assign(manifest, {
  name: `${config.appName} — متتبّع القراءة`,
  short_name: config.appName,
  description: config.description,
  background_color: config.backgroundColor,
  theme_color: config.themeColor
});
await writeFile(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`, "utf8");

const indexPath = join(root, "index.html");
let html = await readFile(indexPath, "utf8");
html = html
  .replace(/<meta name="theme-color" content="[^"]*">/, `<meta name="theme-color" content="${config.themeColor}">`)
  .replace(/<meta name="description" content="[^"]*">/, `<meta name="description" content="${config.appName} — ${config.description}">`)
  .replace(/<meta name="application-name" content="[^"]*">/, `<meta name="application-name" content="${config.appName}">`)
  .replace(/<meta name="apple-mobile-web-app-title" content="[^"]*">/, `<meta name="apple-mobile-web-app-title" content="${config.appName}">`)
  .replace(/<title>[^<]*<\/title>/, `<title>${config.appName} | متتبّع القراءة</title>`);
await writeFile(indexPath, html, "utf8");

console.log(`Synchronized PWA identity: ${config.appName}`);
